    /// Builds a seed place with a stable, deterministic ID so seeded data is
    /// identical on every first launch.
    private static func place(_ n: Int,
                              _ name: String,
                              _ type: PlaceType,
                              _ town: String,
                              _ address: String,
                              _ listedRating: Double?,
                              _ priceLevel: String?,
                              _ hours: String?,
                              _ notes: String,
                              _ tags: [String]) -> Place {
        let digits = String(format: "%012d", n)
        let uuid = UUID(uuidString: "00000000-0000-0000-0000-\(digits)") ?? UUID()
        return Place(
            id: uuid,
            name: name,
            type: type,
            town: town,
            address: address,
            listedRating: listedRating,
            priceLevel: priceLevel,
            hours: hours,
            notes: notes,
            tags: tags,
            addedBy: nil,
            latitude: coordinates[n]?.latitude,
            longitude: coordinates[n]?.longitude
        )
    }
